#!/usr/bin/env python3
"""Convert a PNG to a 4-bit grey C header for platform/gfx/gray.h (Gray4 / blitGray).

    .venv/bin/python host/img2gray.py sprite.png --name ship --width 32 -o firmware/src/ship.h

Pixels are packed two per byte, the left pixel in the high nibble, rows padded to whole bytes
(stride = (w + 1) / 2). Nibble 0 is black, 15 is white; blitGray dithers them to 17 levels.

  --width/--height  resize (one of them keeps the aspect ratio)
  --gamma G         v' = v ** G on the 0..1 brightness: above 1 darkens, below 1 lightens
                    (the panel looks darker than a monitor; try 0.7 for photos)
  --invert          swap black and white
  --transparent     pixels with alpha < 128 become nibble 0, everything else is raised to at
                    least 1, so blitGray(..., transparent = 0) leaves them out
Alpha is otherwise composited on white.
"""
import argparse
import os
import sys

from PIL import Image


def convert(path, width=None, height=None, gamma=1.0, invert=False, transparent=False):
    im = Image.open(path).convert("RGBA")
    if width or height:
        w = width or max(1, round(im.width * height / im.height))
        h = height or max(1, round(im.height * width / im.width))
        im = im.resize((w, h), Image.LANCZOS)
    alpha = im.getchannel("A")
    bg = Image.new("RGBA", im.size, (255, 255, 255, 255))
    grey = Image.alpha_composite(bg, im).convert("L")
    w, h = grey.size
    nib = []
    for y in range(h):
        row = []
        for x in range(w):
            v = (grey.getpixel((x, y)) / 255.0) ** gamma
            n = int(round(v * 15))
            if invert:
                n = 15 - n
            if transparent:
                n = 0 if alpha.getpixel((x, y)) < 128 else max(1, n)
            row.append(max(0, min(15, n)))
        nib.append(row)
    stride = (w + 1) // 2
    data = []
    for row in nib:
        for i in range(stride):
            hi = row[2 * i]
            lo = row[2 * i + 1] if 2 * i + 1 < w else 0
            data.append(hi << 4 | lo)
    return w, h, stride, data


def header(name, w, h, stride, data, source):
    up = name.upper()
    lines = [f"// Generated by host/img2gray.py from {source}. 4 bits per pixel, high nibble = left pixel.",
             "#pragma once", "#include <stdint.h>",
             f"static const int {up}_W = {w}, {up}_H = {h}, {up}_STRIDE = {stride};",
             f"static const uint8_t {up}_DATA[{len(data)}] = {{"]
    for i in range(0, len(data), 16):
        lines.append("  " + ", ".join(f"0x{b:02X}" for b in data[i:i + 16]) + ",")
    lines.append("};")
    lines.append(f"// use: Gray4 g{{{up}_DATA, {up}_W, {up}_H, {up}_STRIDE}};")
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("png")
    ap.add_argument("--name", help="C identifier prefix (default: file name)")
    ap.add_argument("--width", type=int)
    ap.add_argument("--height", type=int)
    ap.add_argument("--gamma", type=float, default=1.0)
    ap.add_argument("--invert", action="store_true")
    ap.add_argument("--transparent", action="store_true")
    ap.add_argument("-o", "--out", help="output header (default: stdout)")
    a = ap.parse_args()
    name = a.name or os.path.splitext(os.path.basename(a.png))[0].replace("-", "_")
    w, h, stride, data = convert(a.png, a.width, a.height, a.gamma, a.invert, a.transparent)
    text = header(name, w, h, stride, data, os.path.basename(a.png))
    if a.out:
        with open(a.out, "w") as f:
            f.write(text)
        print(f"{a.out}: {w}x{h}, {len(data)} bytes", file=sys.stderr)
    else:
        sys.stdout.write(text)


if __name__ == "__main__":
    main()
