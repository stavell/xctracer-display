"""Write firmware/emu/wind_fixtures.h: speed/course excerpts of real flights for the wind regression tests.
  python host/make_wind_fixture.py sve=2026-08-16-XCT-SVE-09.igc:4000:420 sopot=sopot-2026-09-20-XCT-SUI-01.igc:1500:420 \
      > firmware/emu/wind_fixtures.h
Each excerpt is `name=file:start_s:seconds` (start counted from the first fix of the log).
Speed is stored in 0.1 km/h, course in 0.1 degree, one pair per second (the wind maths needs nothing else)."""
import os
import sys
from igc import read_igc

print("#pragma once")
print("// Generated by host/make_wind_fixture.py " + " ".join(os.path.basename(a) for a in sys.argv[1:]) + " -- speed (0.1 km/h), course (0.1 deg) per second.")
print("#include <stdint.h>")
for arg in sys.argv[1:]:
    name, rest = arg.split("=")
    path, start, secs = rest.split(":")
    date, fx = read_igc(path)
    t0 = fx[0].t
    sel = [f for f in fx if int(start) <= f.t - t0 < int(start) + int(secs)]
    print(f"static const int {name}_N = {len(sel)};")
    print(f"static const uint16_t {name}_SC[{len(sel)}][2] = {{")
    row = []
    for f in sel:
        row.append("{%d,%d}" % (round(f.speed * 10), round(f.course * 10) % 3600))
        if len(row) == 10:
            print("  " + ",".join(row) + ",")
            row = []
    if row:
        print("  " + ",".join(row) + ",")
    print("};")
